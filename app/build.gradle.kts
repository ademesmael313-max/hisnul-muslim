// Release signing: fill in keystore.properties (see README) to sign for Play Store.
// Without it, release builds are signed with the debug key so they stay installable.
val keystoreProps = Properties()
val keystorePropsFile = rootProject.file("keystore.properties")
if (keystorePropsFile.exists()) {
    keystorePropsFile.inputStream().use { keystoreProps.load(it) }
}

android {
    lint {
        abortOnError = true
        checkReleaseBuilds = false
        textReport = true
        textOutput = file("stdout")
    }

    namespace = "com.hisnulmuslim.amharic"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.hisnulmuslim.amharic"
        minSdk = 24
        targetSdk = 34
        versionCode = 1
        versionName = "1.0.0"

        resourceConfigurations += listOf("am")
    }

    signingConfigs {
        if (keystorePropsFile.exists()) {
            create("release") {
                storeFile = file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            signingConfig = if (keystorePropsFile.exists()) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug") // preview builds stay installable
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

